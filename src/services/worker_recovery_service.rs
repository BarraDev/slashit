//! Inspecting an interrupted Worker's preserved evidence and accepting one
//! exact commit as its result.

use serde::{Deserialize, Serialize};
use uuid::Uuid;
use wasm_bindgen::prelude::*;
use wasm_bindgen_futures::JsFuture;

use crate::models::Task;

#[wasm_bindgen]
extern "C" {
    #[wasm_bindgen(js_namespace = ["window", "__TAURI__", "core"], js_name = invoke)]
    fn raw_invoke(cmd: &str, args: JsValue) -> js_sys::Promise;
}

async fn invoke<T: for<'de> Deserialize<'de>>(cmd: &str, args: serde_json::Value) -> Result<T, String> {
    let args = serde_wasm_bindgen::to_value(&args).map_err(|e| e.to_string())?;
    let response = JsFuture::from(raw_invoke(cmd, args)).await.map_err(|e| {
        e.as_string().unwrap_or_else(|| {
            js_sys::JSON::stringify(&e)
                .ok()
                .and_then(|s| s.as_string())
                .unwrap_or_else(|| format!("{cmd} failed"))
        })
    })?;
    serde_wasm_bindgen::from_value(response).map_err(|e| e.to_string())
}

/// Mirrors the backend `EvidenceCommit`.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
pub struct EvidenceCommit {
    pub sha: String,
    pub subject: String,
}

/// Mirrors the backend `CheckoutEvidence`.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
pub struct CheckoutEvidence {
    pub path: String,
    pub exists: bool,
    pub registered: bool,
    pub head: Option<String>,
    pub clean: Option<bool>,
    pub dirty_paths: Vec<String>,
}

/// Mirrors the backend `WorkerRecoveryEvidence`.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
pub struct WorkerRecoveryEvidence {
    pub task_id: Uuid,
    pub project_id: Uuid,
    pub repository_id: Option<Uuid>,
    pub stage: String,
    pub reason: Option<String>,
    pub run: Option<u32>,
    pub branch: Option<String>,
    pub start_head: Option<String>,
    pub observed_commit: Option<String>,
    pub branch_tip: Option<String>,
    pub commits: Vec<EvidenceCommit>,
    pub commits_truncated: bool,
    pub checkout: Option<CheckoutEvidence>,
    pub active_execution: bool,
    pub eligible: bool,
    pub refusals: Vec<String>,
}

/// Mirrors the backend `AcceptWorkerResultRequest`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct AcceptWorkerResultRequest {
    pub decision_id: Uuid,
    pub task_id: Uuid,
    pub project_id: Uuid,
    pub repository_id: Uuid,
    pub run: u32,
    pub stage: String,
    pub branch: String,
    pub checkout: String,
    pub observed_commit: Option<String>,
    pub tip: String,
}

impl AcceptWorkerResultRequest {
    /// The request that accepts exactly what `evidence` shows, or `None` when
    /// the snapshot lacks a fact the decision must be bound to. `decision_id`
    /// is generated by the caller once per confirmation, so a repeated click
    /// repeats the same decision rather than making a new one.
    pub fn for_evidence(evidence: &WorkerRecoveryEvidence, decision_id: Uuid) -> Option<Self> {
        Some(Self {
            decision_id,
            task_id: evidence.task_id,
            project_id: evidence.project_id,
            repository_id: evidence.repository_id?,
            run: evidence.run?,
            stage: evidence.stage.clone(),
            branch: evidence.branch.clone()?,
            checkout: evidence.checkout.as_ref()?.path.clone(),
            observed_commit: evidence.observed_commit.clone(),
            tip: evidence.branch_tip.clone()?,
        })
    }
}

/// Mirrors the backend `AcceptWorkerResultOutcome`.
#[derive(Debug, Clone, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum AcceptWorkerResultOutcome {
    Accepted { task: Task },
    AlreadyApplied { task: Task },
    Refused { reason: String },
    DurabilityUnconfirmed { task: Task, detail: String },
}

pub async fn get_worker_recovery_evidence(task_id: String) -> Result<WorkerRecoveryEvidence, String> {
    invoke("get_worker_recovery_evidence", serde_json::json!({ "taskId": task_id })).await
}

pub async fn accept_worker_result(
    request: AcceptWorkerResultRequest,
) -> Result<AcceptWorkerResultOutcome, String> {
    invoke("accept_worker_result", serde_json::json!({ "request": request })).await
}

#[cfg(test)]
mod tests {
    use super::*;

    fn evidence() -> WorkerRecoveryEvidence {
        WorkerRecoveryEvidence {
            task_id: Uuid::from_u128(1),
            project_id: Uuid::from_u128(2),
            repository_id: Some(Uuid::from_u128(3)),
            stage: "recovery_required".into(),
            reason: Some("interrupted".into()),
            run: Some(2),
            branch: Some("task/one".into()),
            start_head: Some("a".repeat(40)),
            observed_commit: None,
            branch_tip: Some("b".repeat(40)),
            commits: Vec::new(),
            commits_truncated: false,
            checkout: Some(CheckoutEvidence {
                path: "/work/one".into(),
                exists: true,
                registered: true,
                head: Some("b".repeat(40)),
                clean: Some(true),
                dirty_paths: Vec::new(),
            }),
            active_execution: false,
            eligible: true,
            refusals: Vec::new(),
        }
    }

    #[test]
    fn the_request_binds_every_fact_the_person_was_shown() {
        let id = Uuid::from_u128(9);
        let request = AcceptWorkerResultRequest::for_evidence(&evidence(), id).unwrap();
        assert_eq!(request.decision_id, id);
        assert_eq!(request.run, 2);
        assert_eq!(request.tip, "b".repeat(40));
        assert_eq!(request.checkout, "/work/one");
        assert_eq!(request.stage, "recovery_required");
    }

    #[test]
    fn evidence_without_an_exact_tip_or_checkout_cannot_be_turned_into_a_decision() {
        let id = Uuid::from_u128(9);
        let mut no_tip = evidence();
        no_tip.branch_tip = None;
        assert!(AcceptWorkerResultRequest::for_evidence(&no_tip, id).is_none());
        let mut no_checkout = evidence();
        no_checkout.checkout = None;
        assert!(AcceptWorkerResultRequest::for_evidence(&no_checkout, id).is_none());
    }
}
